// The lookup binary-searches, so an unsorted or overlapping table would answer
// wrongly for codepoints it does contain rather than failing loudly.
template <std::size_t Count>
[[nodiscard]] constexpr bool ranges_are_ordered(
    const std::array<CodepointRange, Count>& ranges) noexcept {
    for (std::size_t index = 0U; index < Count; ++index) {
        if (ranges[index].begin > ranges[index].end) return false;
        if (index != 0U && ranges[index].begin <= ranges[index - 1U].end) {
            return false;
        }
    }
    return true;
}

