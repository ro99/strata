static_assert(ranges_are_ordered(kLagunaLetterRanges));
static_assert(ranges_are_ordered(kLagunaNumberRanges));
static_assert(ranges_are_ordered(kLagunaSpaceRanges));

template <std::size_t Count>
[[nodiscard]] constexpr bool in_ranges(
    const std::array<CodepointRange, Count>& ranges,
    std::uint32_t codepoint) noexcept {
    std::size_t low = 0U;
    std::size_t high = Count;
    while (low < high) {
        const auto middle = low + (high - low) / 2U;
        if (codepoint < ranges[middle].begin) {
            high = middle;
        } else if (codepoint > ranges[middle].end) {
            low = middle + 1U;
        } else {
            return true;
        }
    }
    return false;
}

[[nodiscard]] constexpr bool laguna_letter(std::uint32_t codepoint) noexcept {
    return in_ranges(kLagunaLetterRanges, codepoint);
}

[[nodiscard]] constexpr bool laguna_number(std::uint32_t codepoint) noexcept {
    return in_ranges(kLagunaNumberRanges, codepoint);
}

[[nodiscard]] constexpr bool laguna_space(std::uint32_t codepoint) noexcept {
    return in_ranges(kLagunaSpaceRanges, codepoint);
}

