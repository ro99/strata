constexpr std::size_t kEntries = 1700U;
static_assert(kRankingHex.size() == 4U * kEntries);

constexpr std::uint16_t nibble(char value) noexcept {
    return value >= '0' && value <= '9'
        ? static_cast<std::uint16_t>(value - '0')
        : static_cast<std::uint16_t>(value - 'a' + 10);
}

constexpr auto decode_ranking() noexcept {
    std::array<std::uint16_t, kEntries> ranking{};
    for (std::size_t index = 0U; index < ranking.size(); ++index) {
        const auto offset = 4U * index;
        ranking[index] = static_cast<std::uint16_t>(
            (nibble(kRankingHex[offset]) << 12U) |
            (nibble(kRankingHex[offset + 1U]) << 8U) |
            (nibble(kRankingHex[offset + 2U]) << 4U) |
            nibble(kRankingHex[offset + 3U]));
    }
    return ranking;
}

constexpr auto kRanking = decode_ranking();

